public class VariablesyConstantes {

    public static void main(String[] args) {

        // Variables
        String nombre = "Ana";
        String carrera = "Desarrollo de Software";
        String materia = "Programación Procedural";

        // Constantes
        final String MENSAJE_BIENVENIDA = "¡Estoy aprendiendo Java!";

        System.out.println("================================");
        System.out.println("     Usando Variables y Constantes");
        System.out.println("================================");

        System.out.println();

        System.out.println("Nombre: " + nombre);
        System.out.println("Carrera: " + carrera);
        System.out.println("Materia: " + materia);

        System.out.println();

        System.out.println(MENSAJE_BIENVENIDA);
    }
}